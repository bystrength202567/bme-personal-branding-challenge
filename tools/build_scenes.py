def build():
    os.makedirs(OUT, exist_ok=True)
    made = []
    for sc in SCENES:
        stem = "scene-%02d-%s" % (sc["num"], sc["name"])
        sk = Sketch(W, H, seed=100 + sc["num"])
        for el in sc["elements"]:
            el[7](sk)
        sk.save(os.path.join(OUT, stem + ".png"))

        elements, boxes = [], []
        for i, (eid, label, role, region, start, dur, sub, _fn) in enumerate(sc["elements"], 1):
            x, y, w, h = region
            assert 0 <= x and 0 <= y and x + w <= W and y + h <= H, (stem, eid, region)
            # 영역은 서로 떨어져 있거나, 뒤 영역이 앞 영역에 완전히 포함되어야 한다.
            # (마스크가 뒤 영역을 앞 영역에서 빼주므로 완전 포함은 골든서클처럼 의도적으로 쓴다.)
            for (px, py, pw, ph), pid in boxes:
                overlaps = x < px + pw and px < x + w and y < py + ph and py < y + h
                inside = px <= x and py <= y and x + w <= px + pw and y + h <= py + ph
                if overlaps and not inside:
                    raise SystemExit("[err] %s: 영역 부분겹침 %s ↔ %s" % (stem, pid, eid))
            boxes.append((region, eid))
            elements.append({
                "id": eid, "label": label, "sequence": i,
                "narrativeRole": role, "subtitle": sub, "type": "structure",
                "region": {"x": int(x), "y": int(y), "width": int(w), "height": int(h)},
                "reveal": {"direction": "top_to_bottom", "startMs": int(start),
                           "durationMs": int(dur), "maskPaddingPx": 16,
                           "protectedRegions": []},
                "handPath": {"start": [int(x + w / 2), int(y)],
                             "end": [int(x + w / 2), int(y + h)], "easing": "easeInOut"},
            })
        last = max(e["reveal"]["startMs"] + e["reveal"]["durationMs"] for e in elements)
        scene_ms = sc["end"] - sc["start"]
        assert last + 500 <= scene_ms, (stem, last, scene_ms)
        with open(os.path.join(OUT, stem + ".annotation.json"), "w", encoding="utf-8") as f:
            json.dump({"sceneId": "scene-%02d" % sc["num"],
                       "canvas": {"width": W, "height": H},
                       "storyBasis": sc["basis"], "sceneDurationMs": scene_ms,
                       "srtRange": {"startMs": sc["start"], "endMs": sc["end"]},
                       "elements": elements}, f, ensure_ascii=False, indent=2)
        made.append((stem, scene_ms, len(elements), last))
    for stem, ms, n, last in made:
        print("%-42s %6.1fs  요소 %2d  (마지막 %.1fs)" % (stem, ms / 1000, n, last / 1000))
    print("장면 %d개 · 합계 %.1fs · 요소 %d개"
          % (len(made), sum(m[1] for m in made) / 1000, sum(m[2] for m in made)))


if __name__ == "__main__":
    build()
